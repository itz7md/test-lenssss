export function normalizeBrandText(str?: string | null): string {
  if (!str) return '';
  return str
    .toLowerCase()
    .trim()
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ڤ/g, 'ف')
    .replace(/[\s\-_]+/g, '');
}

export function getBrandName(
  rawBrand: string | undefined | null,
  lang: 'ar' | 'en' = 'ar',
  preferShort = false
): string {
  if (!rawBrand) return '';
  const clean = rawBrand.trim();
  const lower = clean.toLowerCase();
  if (BRAND_DICTIONARY[lower]) {
    const item = BRAND_DICTIONARY[lower];
    return lang === 'en' ? (preferShort ? item.shortEn : item.en) : (preferShort ? item.shortAr : item.ar);
  }
  const norm = normalizeBrandText(clean);
  for (const [key, item] of Object.entries(BRAND_DICTIONARY)) {
    if (normalizeBrandText(key) === norm) {
      return lang === 'en' ? (preferShort ? item.shortEn : item.en) : (preferShort ? item.shortAr : item.ar);
    }
  }
  return clean;
}

export function matchesBrand(
  brandA?: string | null,
  brandB?: string | null
): boolean {
  if (!brandA || !brandB) return false;
  if (brandB === 'all' || brandA === 'all') return true;

  const cleanA = brandA.trim().toLowerCase();
  const cleanB = brandB.trim().toLowerCase();
  if (cleanA === cleanB) return true;

  const normA = normalizeBrandText(brandA);
  const normB = normalizeBrandText(brandB);
  if (normA === normB || normA.includes(normB) || normB.includes(normA)) return true;

  const dictA = BRAND_DICTIONARY[cleanA] || Object.values(BRAND_DICTIONARY).find(v => normalizeBrandText(v.ar) === normA || normalizeBrandText(v.en) === normA);
  const dictB = BRAND_DICTIONARY[cleanB] || Object.values(BRAND_DICTIONARY).find(v => normalizeBrandText(v.ar) === normB || normalizeBrandText(v.en) === normB);

  if (dictA && dictB && dictA.slug === dictB.slug) return true;
  if (dictA && (normalizeBrandText(dictA.ar) === normB || normalizeBrandText(dictA.en) === normB || dictA.slug === cleanB)) return true;
  if (dictB && (normalizeBrandText(dictB.ar) === normA || normalizeBrandText(dictB.en) === normA || dictB.slug === cleanA)) return true;

  return false;
}

export function getCanonicalBrandSlug(brand?: string | null): string {
  if (!brand) return '';
  const clean = brand.trim().toLowerCase();
  if (BRAND_DICTIONARY[clean]?.slug) return BRAND_DICTIONARY[clean].slug;
  const norm = normalizeBrandText(brand);
  for (const item of Object.values(BRAND_DICTIONARY)) {
    if (normalizeBrandText(item.ar) === norm || normalizeBrandText(item.en) === norm) {
      return item.slug;
    }
  }
  return clean.replace(/\s+/g, '-');
}

export function getBrandFromSegment(seg?: string | null): string | null {
  if (!seg) return null;
  const clean = seg.trim().toLowerCase();
  if (BRAND_DICTIONARY[clean]?.ar) return BRAND_DICTIONARY[clean].ar;
  const norm = normalizeBrandText(seg);
  for (const item of Object.values(BRAND_DICTIONARY)) {
    if (item.slug === clean || normalizeBrandText(item.en) === norm || normalizeBrandText(item.ar) === norm) {
      return item.ar;
    }
  }
  return null;
}

